#!/usr/bin/env node
"use strict";

// Run `node lib/help-guides-bundle.cjs` after editing docs/guides. Bundles the in-app help guides from docs/guides/*.md into a TS module, so the
// desktop app can show them offline. Relative links are rewritten to GitHub,
// because a relative path means nothing inside the packaged app.
const fs = require("node:fs");
const path = require("node:path");

const root = path.resolve(__dirname, "..");
const REPO_BLOB = "https://github.com/flik-lab/layang/blob/main/";
const GUIDES = [{ id: "mockQuickstart", file: "docs/guides/mock-quickstart.md" }];
const OUTPUT = path.join(root, "app/playground/features/help/help-guides.generated.ts");

function rewriteRelativeLinks(markdown, file) {
  const dir = path.posix.dirname(file);
  return markdown.replace(/\]\((?!https?:|#|mailto:)([^)]+)\)/g, (_match, target) =>
    `](${REPO_BLOB}${path.posix.normalize(path.posix.join(dir, target))})`);
}

function render() {
  const entries = GUIDES.map(({ id, file }) => {
    const markdown = fs.readFileSync(path.join(root, file), "utf8").replace(/\r\n/g, "\n");
    return `  ${id}: ${JSON.stringify(rewriteRelativeLinks(markdown, file))},`;
  });
  return `// Generated by lib/help-guides-bundle.cjs from docs/guides. Do not edit by hand.\nexport const HELP_GUIDES = {\n${entries.join("\n")}\n} as const;\n`;
}

if (require.main === module) {
  fs.writeFileSync(OUTPUT, render());
  console.log(`Bundled ${GUIDES.length} help guide(s).`);
}

module.exports = { render, OUTPUT };
