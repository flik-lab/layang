"use strict";
// Build a self-contained classic worker for both file:// Electron and Next dev.
// Keep protobuf's bundled license header; no CDN or renderer module loader.
const fs = require("node:fs");
const path = require("node:path");
const ts = require("typescript");
const root = path.resolve(__dirname, "..");
const runtime = fs.readFileSync(require.resolve("protobufjs/dist/protobuf.min.js"), "utf8");
const loader = ts.transpileModule(fs.readFileSync(path.join(root, "lib/proto-loader.ts"), "utf8"), {
  compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.CommonJS },
}).outputText;
const bundle = `// Generated by scripts/build-proto-catalog-worker.cjs; do not edit.\n
const bundledProtobuf = (() => { const module = {exports:{}}; const exports = module.exports;
${runtime}
return module.exports; })();
const loadProtoFiles = (() => { const exports = {}; const require = name => {
  if (name === "protobufjs") return bundledProtobuf;
  throw new Error("Unexpected worker dependency: " + name);
};
${loader}
return exports.loadProtoFiles; })();
self.onmessage = event => {
  try { self.postMessage({methods: loadProtoFiles(event.data).methods}); }
  catch (error) { self.postMessage({error: String(error.message || error)}); }
};\n`;
const output = path.join(root, "public/workers/proto-catalog.worker.js");
fs.mkdirSync(path.dirname(output), {recursive:true});
fs.writeFileSync(output, bundle);
console.log("Built self-contained proto catalog worker.");
