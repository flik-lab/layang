"use strict";
// Build self-contained classic workers for both file:// Electron and Next dev.
// Keep protobuf's bundled license header; no CDN or renderer module loader.
// protobufjs generates codecs with `new Function`; the renderer CSP has no
// 'unsafe-eval', but workers loaded from their own file do not inherit it, so
// everything that needs protobufjs codegen in the renderer runs in these.
const fs = require("node:fs");
const path = require("node:path");
const ts = require("typescript");
const root = path.resolve(__dirname, "..");
// Optional output directory (tests build into a temp dir); defaults to public/workers.
const outputDirectory = path.resolve(process.argv[2] || path.join(root, "public/workers"));
const runtime = fs.readFileSync(require.resolve("protobufjs/dist/protobuf.min.js"), "utf8");
const loader = ts.transpileModule(fs.readFileSync(path.join(root, "lib/proto-loader.ts"), "utf8"), {
  compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.CommonJS },
}).outputText;
const bundle = `// Generated by scripts/build-proto-catalog-worker.cjs; do not edit.\n
const bundledProtobuf = (() => { const module = {exports:{}}; const exports = module.exports;
${runtime}
return module.exports; })();
const loadProtoFiles = (() => { const exports = {}; const require = name => {
  if (name === "protobufjs") return bundledProtobuf;
  throw new Error("Unexpected worker dependency: " + name);
};
${loader}
return exports.loadProtoFiles; })();
self.onmessage = event => {
  try { self.postMessage({methods: loadProtoFiles(event.data).methods}); }
  catch (error) { self.postMessage({error: String(error.message || error)}); }
};\n`;
const output = path.join(outputDirectory, "proto-catalog.worker.js");
fs.mkdirSync(outputDirectory, {recursive:true});
fs.writeFileSync(output, bundle);
console.log("Built self-contained proto catalog worker.");

// gRPC-Web request encoder: the exact encodeGrpcWebRequestPayload from
// lib/grpc-web-client.ts (with the helpers it calls), so page and worker share
// one implementation and one set of error messages.
const ENCODER_FUNCTIONS = ["encodeGrpcWebRequestPayload", "normalizeProtobufRequestObject", "isPlainObject", "ensureObject"];
function extractFunctions(file, names) {
  const sourceFile = ts.createSourceFile(file, fs.readFileSync(path.join(root, file), "utf8"), ts.ScriptTarget.ES2022, true);
  const found = new Map();
  for (const statement of sourceFile.statements) {
    if (ts.isFunctionDeclaration(statement) && statement.name && names.includes(statement.name.text)) {
      found.set(statement.name.text, statement.getText(sourceFile).replace(/^export\s+/, ""));
    }
  }
  const missing = names.filter(name => !found.has(name));
  if (missing.length) throw new Error(`${file} no longer defines: ${missing.join(", ")}`);
  return ts.transpileModule(`import type * as protobuf from "protobufjs";\n${names.map(name => found.get(name)).join("\n\n")}`, {
    compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.CommonJS },
  }).outputText;
}
const fieldNames = fs.readFileSync(path.join(root, "lib/grpc-request-field-names.cjs"), "utf8");
const encoderSource = extractFunctions("lib/grpc-web-client.ts", ENCODER_FUNCTIONS);
const encoderBundle = `// Generated by scripts/build-proto-catalog-worker.cjs; do not edit.\n
const bundledProtobuf = (() => { const module = {exports:{}}; const exports = module.exports;
${runtime}
return module.exports; })();
const { normalizeRequestFieldNames } = (() => { const module = {exports:{}}; const exports = module.exports;
${fieldNames}
return module.exports; })();
const encodeGrpcWebRequestPayload = (() => { const exports = {};
${encoderSource}
return encodeGrpcWebRequestPayload; })();
// Parsed roots by the page's root key, least recently used first.
const roots = new Map();
const MAX_ROOTS = 8;
function rootFor(key, rootJson) {
  let cached = roots.get(key);
  if (cached) roots.delete(key);
  else if (rootJson) { cached = bundledProtobuf.Root.fromJSON(rootJson); cached.resolveAll(); }
  else return null;
  roots.set(key, cached);
  while (roots.size > MAX_ROOTS) roots.delete(roots.keys().next().value);
  return cached;
}
self.onmessage = event => {
  const { id, key, rootJson, requestType, requestJson } = event.data || {};
  try {
    const schema = rootFor(key, rootJson);
    if (!schema) { self.postMessage({ id, missingSchema: true }); return; }
    // finish() may return a view into a pooled buffer; copy into its own buffer to transfer it.
    const payload = Uint8Array.from(encodeGrpcWebRequestPayload(schema.lookupType(requestType), requestJson));
    self.postMessage({ id, payload }, [payload.buffer]);
  } catch (error) {
    self.postMessage({ id, error: String((error && error.message) || error) });
  }
};\n`;
const encoderOutput = path.join(outputDirectory, "grpc-web-request-encoder.worker.js");
fs.writeFileSync(encoderOutput, encoderBundle);
console.log("Built self-contained gRPC-Web request encoder worker.");
